"""Generate a small homepage, paginated catalog, and stable paper detail pages."""
from __future__ import annotations

import json
import re
from datetime import date, timedelta
from pathlib import Path

import yaml
from jinja2 import ChainableUndefined, Environment, FileSystemLoader

from curation import WEIGHTS, compute_total, derive_priority, sort_key

ROOT = Path(__file__).resolve().parents[1]
MARKER = '<!-- Generated by scripts/generate_readme.py; do not edit. -->'
PAGE_SIZE = 15
HOME_PICKS = 5
SCORE_EXAMPLE = {'C': 4, 'E': 4, 'O': 3, 'T': 3}


def load(name, key):
    return (yaml.safe_load((ROOT / 'data' / name).read_text(encoding='utf-8')) or {}).get(key, [])


def brief(text, limit=110):
    text = ' '.join(str(text or '').split())
    if len(text) <= limit:
        return text
    prefix = text[:limit]
    for separator in ('。', '；', '; ', '. '):
        end = prefix.rfind(separator)
        if end > limit // 2:
            return prefix[:end + len(separator)]
    return prefix.rstrip(' ,，;；') + '…'


def page_name(category, number):
    return category + (f'-{number}' if number > 1 else '') + '.md'


def render_all():
    cats = sorted(load('categories.yaml', 'categories'), key=lambda c: c.get('order', 999))
    papers = load('papers.yaml', 'papers')
    resources = {key: load(key + '.yaml', key) for key in ('datasets', 'simulators', 'benchmarks', 'tools', 'companies')}
    runs = load('runs.yaml', 'runs')
    latest_scan = max((str(r['scan_date']) for r in runs if r.get('kind') == 'daily'), default='unknown')
    for p in papers:
        p.setdefault('review', {'priority': 'unrated'})
        p.setdefault('open', {})
        if not re.fullmatch(r'\d{4}\.\d{4,5}', str(p['arxiv_id'])):
            raise ValueError(f"Unsafe paper id: {p['arxiv_id']}")
        p['detail'] = f"docs/papers/{p['arxiv_id']}.md"
    research = []
    groups = []
    for cat in cats:
        if cat.get('source'):
            continue
        entries = []
        for sub in cat.get('subcategories', []) + [{'id': cat['id'], 'title': cat['title']}]:
            items = sorted((p for p in papers if p['category'] == sub['id']), key=sort_key)
            if not items and sub['id'] == cat['id'] and cat.get('subcategories'):
                continue
            item = dict(sub, papers=items, count=len(items), path=f"docs/catalog/{sub['id']}.md", parent=cat['id'], desc=cat['desc'])
            research.append(item)
            entries.append(item)
            for p in items:
                p['category_title'] = sub['title']
        groups.append(dict(cat, entries=entries, count=sum(e['count'] for e in entries)))
    known = {c['id'] for c in research}
    if any(p['category'] not in known for p in papers):
        raise ValueError('A paper has no catalog category')
    resource_groups = [dict(c, entries=resources[c['id']], count=len(resources[c['id']]), path=f"docs/resources/{c['id']}.md") for c in cats if c.get('source')]
    used_by = {}
    for p in papers:
        for use in p.get('uses') or []:
            used_by.setdefault(use['resource'], []).append(dict(paper=p, role=use['role']))
    # Date is anchored to the last scan, so re-rendering identical data is stable.
    cutoff = (date.fromisoformat(latest_scan) - timedelta(days=6)).isoformat() if latest_scan != 'unknown' else '9999'
    recent = sorted((p for p in papers if str(p.get('added', '')) >= cutoff and p['review']['priority'] in ('must-read', 'notable')), key=sort_key)
    ranked = sorted((p for p in papers if p['review'].get('total')), key=sort_key)[:20]
    reports = {}
    for kind in ('daily', 'weekly', 'monthly'):
        reports[kind] = [p.relative_to(ROOT).as_posix() for p in sorted((ROOT / 'digests' / kind).glob('*.md'), reverse=True)]
    context = dict(papers=papers, research=research, groups=groups, resource_groups=resource_groups,
                   resources=resources, used_by=used_by, latest_scan=latest_scan, picks=recent[:HOME_PICKS],
                   ranked=ranked, reports=reports, latest_digest=reports['daily'][0] if reports['daily'] else '',
                   score_weights={key: value * 5 for key, value in WEIGHTS.items()},
                   score_example=SCORE_EXAMPLE, example_total=compute_total(SCORE_EXAMPLE),
                   example_formula=' + '.join(f'{SCORE_EXAMPLE[k]}/5 × {v * 5}' for k, v in WEIGHTS.items()),
                   example_priority=derive_priority(SCORE_EXAMPLE),
                   priority_names_en={'must-read':'Must-read', 'notable':'Notable', 'watching':'Watching', 'unrated':'Unrated'},
                   code_names_en={'substantive':'Code released', 'partial':'Partially released', 'placeholder':'Placeholder repository', 'no-repo':'No repository found', 'unknown':'Code status unchecked'},
                   priority_names={'must-read':'重点阅读', 'notable':'值得关注', 'watching':'观察中', 'unrated':'暂不评级'},
                   code_names={'substantive':'实质代码', 'partial':'部分开放', 'placeholder':'占位仓库', 'no-repo':'未找到仓库', 'unknown':'未核查'})
    env = Environment(loader=FileSystemLoader(str(ROOT / 'templates')), trim_blocks=True, lstrip_blocks=True,
                      keep_trailing_newline=True, undefined=ChainableUndefined)
    env.filters['brief'] = brief
    env.filters['cell'] = lambda value: ' '.join(str(value or '').split()).replace('|', '\\|')
    env.filters['label'] = lambda value: str(value or '').replace('[', '\\[').replace(']', '\\]').replace('|', '\\|')
    outputs = {}
    def render(path, template, **extra):
        outputs[path] = MARKER + '\n\n' + env.get_template(template).render(**dict(context, **extra))
    render('README.md', 'README.md.j2')
    render('README.en.md', 'README.en.md.j2')
    # Keep existing Chinese links (including section anchors) working.
    render('README.zh-CN.md', 'README.zh-CN.md.j2')
    render('docs/index.md', 'index.md.j2')
    render('docs/rankings.md', 'rankings.md.j2')
    render('docs/all-papers.md', 'archive.md.j2')
    render('digests/README.md', 'digests.md.j2')
    for cat in research:
        count = max(1, (cat['count'] + PAGE_SIZE - 1) // PAGE_SIZE)
        for number in range(1, count + 1):
            pages = [dict(number=n, name=page_name(cat['id'], n)) for n in range(1, count + 1)]
            render('docs/catalog/' + page_name(cat['id'], number), 'catalog.md.j2', cat=cat, number=number,
                   pages=pages, entries=cat['papers'][(number-1)*PAGE_SIZE:number*PAGE_SIZE], offset=(number-1)*PAGE_SIZE)
    for p in papers:
        render(p['detail'], 'paper.md.j2', p=p)
    for group in resource_groups:
        render(group['path'], 'resources.md.j2', group=group)
    manifest = ROOT / 'docs/.generated-pages.json'
    old = json.loads(manifest.read_text(encoding='utf-8')) if manifest.exists() else []
    for relative in set(old) - set(outputs):
        path = (ROOT / relative).resolve()
        if not path.is_relative_to(ROOT / 'docs'):
            raise ValueError(f'Unsafe stale output: {relative}')
        if path.exists() and path.read_text(encoding='utf-8').startswith(MARKER):
            path.unlink()
    for relative, content in outputs.items():
        path = ROOT / relative
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(content, encoding='utf-8', newline='\n')
    manifest.write_text(json.dumps(sorted(outputs), indent=2) + '\n', encoding='utf-8')
    print(f'Generated {len(outputs)} pages for {len(papers)} papers; homepage picks <= {HOME_PICKS}, catalog page <= {PAGE_SIZE}.')
    return outputs


def main():
    render_all()
    return 0


if __name__ == '__main__':
    main()
